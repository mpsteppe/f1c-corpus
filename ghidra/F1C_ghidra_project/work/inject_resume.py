func_block_re = re.compile(
    r'(\d+\.\s+FUN_[0-9a-fA-F]+\s*\n\s+doc:\s+\S+\s*\n\s+source:\s+\S+)',
    re.MULTILINE
)

APPEND_INJECT = (
    "**APPEND** to (do NOT overwrite):"
    "{path}\n\n"
    "The file already contains completed verdicts. "
    "Before processing each function, check if `## FUN_XXXXXXXX` already appears in the output file — if so, skip it entirely."
)

for letter in "ACEPT":
    done = {a.lower() for a in DONE[letter]}
    pf = PROMPT_DIR / f"worker_{letter}_prompt.md"
    content = pf.read_text(encoding="utf-8", errors="replace")

    blocks = func_block_re.findall(content)
    remaining = [b for b in blocks if re.search(r'(FUN_[0-9a-fA-F]+)', b) and
                 re.search(r'(FUN_[0-9a-fA-F]+)', b).group(1).lower() not in done]

    print(f"{letter}: {len(blocks)} total, {len(done)} done, {len(remaining)} remaining")

    funcs_start = content.find("## YOUR FUNCTIONS")
    funcs_end   = content.find("\n## FOR EACH FUNCTION")
    if funcs_start == -1 or funcs_end == -1:
        print(f"  WARNING: section boundaries not found for {letter}")
        continue

    header = content[:funcs_start]
    instructions = content[funcs_end:]

    # Replace "Write ALL output to:" line with append instruction
    def replace_output_line(m):
        path = m.group(1)
        return f"**APPEND** to (do NOT overwrite):{path}\n\nThe file already contains completed verdicts. Before processing each function, check if `## FUN_XXXXXXXX` already appears in the output file — if so, skip it entirely."

    header = re.sub(r"Write ALL output to:([^\n]+)", replace_output_line, header)

    new_funcs = f"## YOUR REMAINING FUNCTIONS ({len(remaining)})\n\n"
    new_funcs += "\n\n".join(remaining)

    new_content = header + new_funcs + "\n" + instructions
    pf.write_text(new_content, encoding="utf-8")
    print(f"  Updated: {pf.name}")

print("\nAll done.")
